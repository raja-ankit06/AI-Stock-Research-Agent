from datetime import datetime, timezone
from typing import Any, Dict
from app.models.research import ResearchReport


class ReportService:
    """
    Compiles structured research reports into exportable Markdown and styled HTML/PDF artifacts.
    """

    @staticmethod
    def compile_markdown(report: ResearchReport, company_name: str) -> str:
        fund = report.fundamental_payload or {}
        tech = report.technical_payload or {}
        sent = report.sentiment_payload or {}
        risk = report.risk_payload or {}

        now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

        md = f"""# EQUITY RESEARCH REPORT: {report.symbol}
**Company:** {company_name}  
**Synthesized Rating:** **{report.overall_rating.upper()}** (Confidence: {int(report.confidence_score * 100)}%)  
**Generated Date:** {now_str}  
**Classification:** AI Multi-Agent Quantitative & Qualitative Synthesis  

---

## 1. Executive Summary
{report.executive_summary}

---

## 2. Fundamental Analysis & Valuation
**P/E Ratio:** {fund.get('pe_ratio', 'N/A')}x | **P/B Ratio:** {fund.get('pb_ratio', 'N/A')}x  
**Gross Margin:** {f"{fund.get('gross_margin', 0) * 100:.1f}%" if fund.get('gross_margin') is not None else 'N/A'} | **Operating Margin:** {f"{fund.get('operating_margin', 0) * 100:.1f}%" if fund.get('operating_margin') is not None else 'N/A'}  
**Debt-to-Equity:** {fund.get('debt_to_equity', 'N/A')} | **Current Ratio:** {fund.get('current_ratio', 'N/A')}x  

### Key Strengths:
"""
        for s in fund.get("strengths", []):
            md += f"- **{s}**\n"

        md += "\n### Key Weaknesses:\n"
        for w in fund.get("weaknesses", []):
            md += f"- {w}\n"

        md += f"""
---

## 3. Technical Analysis & Price Action
**Overall Trend:** {tech.get('trend', 'Neutral')}  
**Current 20-Day SMA:** ${tech.get('sma_20', 'N/A')} | **50-Day SMA:** ${tech.get('sma_50', 'N/A')} | **200-Day SMA:** ${tech.get('sma_200', 'N/A')}  
**14-Period RSI:** {tech.get('rsi_14', 'N/A')}  
**MACD Status:** {tech.get('macd_status', 'N/A')}  
**Bollinger Band Position:** {tech.get('bollinger_position', 'N/A')}  
**Key Levels:** Support at ${tech.get('support_level', 'N/A')} | Resistance at ${tech.get('resistance_level', 'N/A')}  

### Momentum Summary:
{tech.get('momentum_summary', 'N/A')}

---

## 4. Market Sentiment & Catalyst Analysis
**Composite Sentiment Score:** {sent.get('composite_score', 0.0)} ({sent.get('sentiment_label', 'Neutral')})  
**Articles Analyzed:** {sent.get('articles_analyzed', 0)}  

### Key Corporate Catalysts:
"""
        for cat in sent.get("top_catalysts", []):
            md += f"- {cat}\n"

        md += f"""
---

## 5. Cross-Domain Risk Assessment
**Overall Risk Level:** **{risk.get('overall_risk_level', 'Moderate')}**  
**Beta:** {risk.get('beta', 'N/A')} | **1-Year Max Drawdown:** {f"{risk.get('max_drawdown_1y', 0) * 100:.1f}%" if risk.get('max_drawdown_1y') is not None else 'N/A'}  

### Detected Cross-Domain Contradictions:
"""
        contradictions = risk.get("detected_contradictions", [])
        if contradictions:
            for item in contradictions:
                md += f"- **[{item.get('severity', 'WARNING')}] {item.get('title', '')}:** {item.get('description', '')}\n"
        else:
            md += "- *No acute cross-domain divergences detected between price action and fundamentals.*\n"

        md += f"""
---

## 6. Regulatory & Informational Disclaimer
> **Important Notice:** This document is generated by an artificial intelligence multi-agent system strictly for informational, educational, and research purposes. It does **not** constitute personalized investment advice, financial planning, or an endorsement to buy, sell, or hold any security. Past performance of financial assets is no guarantee of future returns.
"""
        return md.strip()

