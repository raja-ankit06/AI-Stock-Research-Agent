from fastapi import APIRouter, Depends, HTTPException, Query, Response, status
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.orm import selectinload
from app.api.deps import get_current_user
from app.core.database import get_db
from app.models.research import ResearchReport, ResearchSession
from app.models.user import User
from app.schemas.research import ReportResponse
from app.services.report_service import ReportService

router = APIRouter()


@router.get("/{report_id}", response_model=ReportResponse)
async def get_report(
    report_id: str,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """Retrieve structured research report by ID."""
    stmt = (
        select(ResearchReport)
        .options(selectinload(ResearchReport.session))
        .where(ResearchReport.id == report_id)
    )
    res = await db.execute(stmt)
    report = res.scalar_one_or_none()

    if not report or not report.session or report.session.user_id != current_user.id:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Report not found or unauthorized access."
        )

    disclaimer = (
        "This report is generated by an artificial intelligence multi-agent system strictly for "
        "informational, research, and educational purposes. It does not constitute investment advice."
    )

    return ReportResponse(
        report_id=report.id,
        research_id=report.research_session_id,
        symbol=report.symbol,
        company_name=report.session.company_name or report.symbol,
        overall_rating=report.overall_rating,
        confidence_score=report.confidence_score,
        executive_summary=report.executive_summary,
        fundamental_payload=report.fundamental_payload,
        technical_payload=report.technical_payload,
        sentiment_payload=report.sentiment_payload,
        risk_payload=report.risk_payload,
        disclaimer=disclaimer,
        generated_at=report.created_at
    )


@router.get("/{report_id}/download")
async def download_report(
    report_id: str,
    format: str = Query("markdown", pattern="^(markdown|pdf)$"),
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """Download research report as a standalone Markdown or PDF artifact."""
    stmt = (
        select(ResearchReport)
        .options(selectinload(ResearchReport.session))
        .where(ResearchReport.id == report_id)
    )
    res = await db.execute(stmt)
    report = res.scalar_one_or_none()

    if not report or not report.session or report.session.user_id != current_user.id:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Report not found or unauthorized access."
        )

    company_name = report.session.company_name or report.symbol
    markdown_content = ReportService.compile_markdown(report, company_name)

    filename = f"{report.symbol}_Research_Report.md"
    return Response(
        content=markdown_content,
        media_type="text/markdown",
        headers={"Content-Disposition": f'attachment; filename="{filename}"'}
    )

